/**
 * ## Abstract Data Types (ADTs) vs Data Structures
 *
 * An **Abstract Data Type (ADT)** is a theoretical concept that defines what operations
 * can be performed and their expected behavior, without specifying how they're implemented.
 * Examples: List, Queue, Stack, Priority Queue.
 *
 * A **Data Structure** is a concrete implementation of an ADT. It defines how data is
 * organized in memory and how operations are performed. Examples: Array, Linked List,
 * Hash Table, Heap, Binary Search Tree.
 *
 * **Key Distinction:** The same ADT can be implemented using different data structures.
 * For instance, a Queue ADT can be implemented with an Array, Linked List, or Circular Buffer.
 * Each implementation may have different time and space complexity characteristics.
 *
 * This folder contains implementations of common data structures used throughout
 * algorithms and design patterns.
 */
